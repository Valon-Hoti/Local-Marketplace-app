/* ====================================================================
   4. KRIJIMI I POLIKAVE STRIKTE TË SIGURISË (RLS POLICIES)
   ==================================================================== */

/* --- A. PROFILES --- */
/* Kushdo mund të lexojë profilet publike */
CREATE POLICY "Public profiles are viewable by everyone"
ON profiles FOR SELECT
USING (true);

/* Vetëm përdoruesi i kyçur mund të krijojë profilin e tij */
CREATE POLICY "Users can insert their own profile"
ON profiles FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = id);

/* Vetëm përdoruesi mund të modifikojë profilin e tij */
CREATE POLICY "Users can update own profile"
ON profiles FOR UPDATE
TO authenticated
USING (auth.uid() = id)
WITH CHECK (auth.uid() = id);

/* Vetëm përdoruesi mund të fshijë profilin e tij */
CREATE POLICY "Users can delete own profile"
ON profiles FOR DELETE
TO authenticated
USING (auth.uid() = id);


/* --- B. LISTINGS --- */
/* Shpalljet mund të lexohen nga të gjithë vizitorët */
CREATE POLICY "Listings are viewable by everyone"
ON listings FOR SELECT
USING (true);

/* Vetëm përdoruesit e regjistruar mund të postojnë (dhe seller_id duhet të jetë llogaria e tyre) */
CREATE POLICY "Users can create listings"
ON listings FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = seller_id);

/* Vetëm shitësi që e ka krijuar shpalljen mund ta modifikojë atë */
CREATE POLICY "Users can update own listings"
ON listings FOR UPDATE
TO authenticated
USING (auth.uid() = seller_id)
WITH CHECK (auth.uid() = seller_id);

/* Vetëm shitësi mund ta fshijë shpalljen e tij */
CREATE POLICY "Users can delete own listings"
ON listings FOR DELETE
TO authenticated
USING (auth.uid() = seller_id);


/* --- C. MESSAGES (BISEDAT PRIVATE) --- */
/* Vetëm dërguesi, blerësi i bisedës ose shitësi i shpalljes mund t'i lexojë mesazhet */
CREATE POLICY "Users can view their own messages"
ON messages FOR SELECT
TO authenticated
USING (
  auth.uid() = user_id 
  OR (buyer_id IS NOT NULL AND auth.uid() = buyer_id)
  OR auth.uid() IN (SELECT seller_id FROM listings WHERE id = messages.listing_id)
);

/* Përdoruesi i kyçur mund të dërgojë mesazh vetëm me ID-në e tij */
CREATE POLICY "Users can insert messages"
ON messages FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = user_id);

/* Përdoruesi mund të fshijë mesazhet e tij ose shitësi mund të pastrojë bisedat në shpalljen e tij */
CREATE POLICY "Users can delete own messages"
ON messages FOR DELETE
TO authenticated
USING (
  auth.uid() = user_id
  OR auth.uid() IN (SELECT seller_id FROM listings WHERE id = messages.listing_id)
);

/* Marrësi i mesazhit ose shitësi i shpalljes mund të përditësojë 'is_read' */
CREATE POLICY "Users can update received messages"
ON messages FOR UPDATE
TO authenticated
USING (
  auth.uid() = user_id
  OR auth.uid() IN (SELECT seller_id FROM listings WHERE id = messages.listing_id)
)
WITH CHECK (
  auth.uid() = user_id
  OR auth.uid() IN (SELECT seller_id FROM listings WHERE id = messages.listing_id)
);


/* --- D. FAVORITES --- */
/* Përdoruesi mund të shohë vetëm postimet e tij të ruajtura */
CREATE POLICY "Users can view own favorites"
ON favorites FOR SELECT
TO authenticated
USING (auth.uid() = user_id);

/* Përdoruesi mund të ruajë shpallje vetëm për llogarinë e tij */
CREATE POLICY "Users can insert own favorites"
ON favorites FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = user_id);

/* Përdoruesi mund të heqë shpallje nga të ruajturat vetëm për llogarinë e tij */
CREATE POLICY "Users can delete own favorites"
ON favorites FOR DELETE
TO authenticated
USING (auth.uid() = user_id);


/* --- E. SELLER REVIEWS --- */
/* Të gjithë mund të shohin vlerësimet e një shitësi */
CREATE POLICY "Allow all to view reviews"
ON seller_reviews FOR SELECT
USING (true);

/* Përdoruesi mund të vlerësojë vetëm me llogarinë e tij DHE nuk mund të vlerësojë veten */
CREATE POLICY "Allow authenticated to insert reviews"
ON seller_reviews FOR INSERT
TO authenticated
WITH CHECK (
  auth.uid() = reviewer_id 
  AND auth.uid() <> seller_id
);

/* Përdoruesi mund të fshijë/ndryshojë vetëm vlerësimin e vet */
CREATE POLICY "Users can update own reviews"
ON seller_reviews FOR UPDATE
TO authenticated
USING (auth.uid() = reviewer_id)
WITH CHECK (auth.uid() = reviewer_id);


/* --- F. REPORTS (RAPORTIMET) --- */
/* Përdoruesit mund të dërgojnë raportime (edhe anonimë) */
CREATE POLICY "Allow all to submit reports"
ON reports FOR INSERT
WITH CHECK (true);

