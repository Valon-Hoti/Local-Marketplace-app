/* A. Funksion RPC për të rritur shikimet e shpalljes nga çdo vizitor pa komprometuar sigurinë e shpalljes */
CREATE OR REPLACE FUNCTION public.increment_listing_views(listing_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  UPDATE public.listings
  SET views = COALESCE(views, 0) + 1
  WHERE id = listing_id;
END;
$$;

/* B. Krijimi automatik i profilit publik sapo krijohet një llogari e re në auth.users */
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  INSERT INTO public.profiles (id, display_name, avatar_url)
  VALUES (
    NEW.id,
    COALESCE(NEW.raw_user_meta_data->>'username', split_part(NEW.email, '@', 1)),
    NULL
  )
  ON CONFLICT (id) DO UPDATE
    SET display_name = EXCLUDED.display_name
    WHERE profiles.display_name IS NULL OR profiles.display_name = '';
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

